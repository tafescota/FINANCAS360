import assert from 'node:assert/strict';
import vm from 'node:vm';
import {contextoAplicacao} from './test-transfer-cnpj.mjs';
const ctx=contextoAplicacao();
const run=code=>vm.runInContext(code,ctx);
run(`
grupoAtivo='VD';configGrupos={VD:{modoImportacaoPagamentos:'parcelas'}};
extratoBancarioTemp=[{data:new Date(2026,5,5),conta:'CEF VD',valor:-107.7,historico:'REDE MC CC',tipoConciliacao:'Parcelas de Cartões'}];
conciliacaoItensTemp=[{id:'saida-0',movimento:'saida-pendente',idxOriginal:0,total:107.7,data:'05/06/2026',conta:'CEF VD',historico:'REDE MC CC',tipo:'Parcelas de Cartões',chaveRegraSaida:'teste'}];
sugestoesParcelasExtratoTemp=[];
let modalTeste;const criarAnterior=document.createElement;document.createElement=(...args)=>{modalTeste=criarAnterior(...args);return modalTeste;};
abrirModalPendenciasConciliacao();
`);
assert.equal(run(`modalTeste.innerHTML.includes('Este valor ja consta no extrato')`),true);
assert.equal(run(`modalTeste.innerHTML.includes('Marcar como já representada / não exportar')`),false);
assert.equal(run(`modalTeste.innerHTML.includes('virar um lançamento extra')`),false);
run(`codigosConciliacaoTemp['saida-0']='2780';revisarSaidaExtratoSemExportar('saida-0');`);
assert.equal(run(`codigosConciliacaoTemp['saida-0']`),'2780');
assert.equal(run(`saidasExtratoRevisadasConciliacaoTemp['saida-0']`),undefined);
run(`configGrupos.VD.modoImportacaoPagamentos='parcelas_numerarios';codigosConciliacaoTemp['saida-0']='';abrirModalPendenciasConciliacao();`);
assert.equal(run(`modalTeste.innerHTML.includes('Este valor ja consta no extrato')`),true);
assert.equal(run(`modalTeste.innerHTML.includes('Marcar como já representada / não exportar')`),false);
run(`sugestoesParcelasExtratoTemp=[{movs:[extratoBancarioTemp[0]]}];abrirModalPendenciasConciliacao();`);
assert.equal(run(`modalTeste.innerHTML.includes('Marcar como já representada / não exportar')`),true);
run(`configGrupos.VD.modoImportacaoPagamentos='cp_simone';codigosConciliacaoTemp['saida-0']='';abrirModalPendenciasConciliacao();`);
assert.equal(run(`modalTeste.innerHTML.includes('Marcar como já representada / não exportar')`),true);
assert.equal(run(`modalTeste.innerHTML.includes('virar um lançamento extra')`),true);
run(`revisarSaidaExtratoSemExportar('saida-0');`);
assert.equal(run(`saidasExtratoRevisadasConciliacaoTemp['saida-0']`),true);
